RainedVMFrame::RainedVMFrame()
    : wxFrame(nullptr, wxID_ANY, "Rained Version Manager", wxDefaultPosition, wxSize(640, 480))
{
    wxMenu *menuFile = new wxMenu;
    menuFile->Append(wxID_EXIT);

    wxMenu *menuHelp = new wxMenu;
    menuHelp->Append(wxID_ABOUT);

    wxMenuBar *menuBar = new wxMenuBar;
    menuBar->Append(menuFile, "&File");
    menuBar->Append(menuHelp, "&Help");
    SetMenuBar(menuBar);

    mainPanel = new wxPanel(this, wxID_ANY);
    Fetch();

    Bind(wxEVT_LISTBOX, &RainedVMFrame::OnVersionSelect, this, ID_VersionList);
    Bind(wxEVT_BUTTON, &RainedVMFrame::OnInstallButtonPressed, this, ID_InstallButton);
    Bind(wxEVT_TIMER, &RainedVMFrame::OnFetchCheckTimer, this, ID_FetchCheckTimer);
    Bind(wxEVT_MENU, &RainedVMFrame::OnExit, this, wxID_EXIT);
    Bind(wxEVT_MENU, &RainedVMFrame::OnAbout, this, wxID_ABOUT);
}

void RainedVMFrame::Fetch() {
    ConstructFetchPage();
    
    timer = new wxTimer(this, ID_FetchCheckTimer);
    timer->Start(1);
    
    is_vm_fetch_done = false;
    thread = std::make_unique<std::thread>(([this]{
        vm.fetch();
        wxMilliSleep(100);
        is_vm_fetch_done = true;
    }));
}

void RainedVMFrame::ClearPage() {
    if (mainPanel) {
        mainPanel->DestroyChildren();
    }

    installButton = nullptr;
    versionListBox = nullptr;
    versionLabel = nullptr;
    htmlWindow = nullptr;
}

void RainedVMFrame::ConstructFetchPage() {
    ClearPage();

    // mainPanel = new wxPanel(this);
    wxBoxSizer *sizer = new wxBoxSizer(wxVERTICAL);

    sizer->AddStretchSpacer(1);

    sizer->Add(
        new wxStaticText(mainPanel, wxID_ANY, "Fetching version list..."),
        0, wxALL | wxALIGN_CENTER, ITEM_SPACING
    );

    wxGauge *gauge = new wxGauge(mainPanel, wxID_ANY, 100);
    gauge->Pulse();

    sizer->Add(
        gauge,
        0, wxALL | wxALIGN_CENTER, ITEM_SPACING
    );

    sizer->AddStretchSpacer(1);

    mainPanel->SetSizerAndFit(sizer);
    Layout();
}

void RainedVMFrame::ConstructVersionSelector() {
    ClearPage();

    // mainPanel = new wxPanel(this, wxID_ANY);

    // 1. current version
    // 2. sizer1 (horiz)
    wxBoxSizer *sizer0 = new wxBoxSizer(wxVERTICAL);

    // 1. list box
    // 2. sizer2 (vert)
    wxBoxSizer *sizer1 = new wxBoxSizer(wxHORIZONTAL);

    // 1. version changelog
    // 2. install button
    wxBoxSizer *sizer2 = new wxBoxSizer(wxVERTICAL);

    versionLabel =
        new wxStaticText(mainPanel, -1, "Current version: v2.3.2-dev");
    
    if (vm.get_current_version_name().empty()) {
        versionLabel->Hide();
    } else {
        versionLabel->SetLabel("Current version: " + vm.get_current_version_name());
    }

    sizer0->Add(
        versionLabel,
        0,
        wxALL,
        ITEM_SPACING);
    sizer0->Add(sizer1, 1, wxALL | wxEXPAND, ITEM_SPACING);

    wxArrayString versionItems;
    activeVersionIndex = vm.get_current_version_index();
    selectedVersionIndex = activeVersionIndex;

    // compile list of version names, and also determine the index of the active
    // version to have automatically already selected
    const auto &available_versions = vm.get_available_versions();
    for (auto it = available_versions.begin(); it != available_versions.end(); ++it) {
        const auto &info = *it;
        int index = (int)std::distance(available_versions.begin(), it);

        std::string name = info.version_name;
        if (index == activeVersionIndex) {
            name += " (current)";
        }

        versionItems.push_back(name);
    }
    
    // construct the version list box
    versionListBox = new wxListBox(
        mainPanel, ID_VersionList, wxDefaultPosition, wxDefaultSize);
    versionListBox->InsertItems(versionItems, 0);
    if (activeVersionIndex != -1)
        versionListBox->Select(activeVersionIndex);

    sizer1->Add(versionListBox, 0, wxALL | wxEXPAND, ITEM_SPACING);
    sizer1->Add(
        sizer2,
        1,
        wxALL | wxEXPAND,
        ITEM_SPACING);
    
    htmlWindow = new OverriddenHtmlWindow(
        mainPanel, -1, wxDefaultPosition, wxDefaultSize);
    sizer2->Add(
        htmlWindow,
        1, wxALL | wxEXPAND, ITEM_SPACING
    );

    sizer2->Add(
        (installButton = new wxButton(mainPanel, ID_InstallButton, "Install")),
        0, wxALL, ITEM_SPACING
    );

    mainPanel->SetSizerAndFit(sizer0);
    Layout();

    // this is to update the button label correctly
    wxCommandEvent tmp = wxCommandEvent(wxEVT_LISTBOX);
    OnVersionSelect(tmp);
}

void RainedVMFrame::OnFetchCheckTimer(wxTimerEvent &event) {
    (void)event;

    if (is_vm_fetch_done) {
        delete timer;
        timer = nullptr;

        thread->join();
        thread = nullptr;

        wxLogDebug("vm fetch done");
        ConstructVersionSelector();
    }
}

void RainedVMFrame::OnExit(wxCommandEvent &event) {
    (void)event;
    Close(true);
}

void RainedVMFrame::OnAbout(wxCommandEvent &event) {
    (void)event;

    AboutDialog dlg(this, wxID_ANY);
    dlg.ShowModal();
}

void RainedVMFrame::OnVersionSelect(wxCommandEvent &event) {
    (void)event;

    selectedVersionIndex = versionListBox->GetSelection();
    if (activeVersionIndex != -1 && selectedVersionIndex == activeVersionIndex) {
        installButton->SetLabel("Sync");
    } else {
        installButton->SetLabel("Install");
    }

    installButton->Enable(selectedVersionIndex != -1);

    if (selectedVersionIndex != -1) {
        const auto &info = vm.get_available_versions()[selectedVersionIndex];
        std::string htmlOutput = parseMarkdownToHTML(info.changelog);
        htmlWindow->SetPage(htmlOutput);
    } else {
        htmlWindow->SetPage("<html></html>");
    }
}

void RainedVMFrame::OnInstallButtonPressed(wxCommandEvent &event) {
    (void)event;

    if (selectedVersionIndex == -1) return;

    {
        wxProgressDialog dlg(
            "Installing...", "Installing...", 1000, this,
            wxPD_APP_MODAL | wxPD_CAN_ABORT);
        
        std::unique_ptr<InstallTask> task = 
            vm.start_installation(vm.get_available_versions()[selectedVersionIndex]);
        
        while (true) {
            std::string msg;
            float progress;

            if (!task->get_progress(msg, progress)) {
                std::string exceptionMsg;
                if (task->get_exception(exceptionMsg)) {
                    exceptionMsg = "Exception occurred\n\n" + exceptionMsg;
                    wxMessageBox(
                        exceptionMsg, wxMessageBoxCaptionStr,
                        wxOK | wxCENTER | wxICON_ERROR, this);
                }

                task = nullptr;
                break;
            }

            OverwritePromptInfo prompt;
            if (task->get_overwrite_prompt(prompt)) {
                wxMessageDialog dlg(
                    this, "Local changes were detected in " + prompt.display_file_path,
                    "Overwrite?", wxYES_NO | wxCANCEL | wxNO_DEFAULT | wxCENTER);
                
                dlg.SetYesNoCancelLabels("Overwrite Changes", "Keep Changes", "Cancel");
                switch (dlg.ShowModal()) {
                    case wxID_YES:
                        task->set_overwrite_prompt_result(1);
                        break;
                    
                    case wxID_NO:
                        task->set_overwrite_prompt_result(0);
                        break;

                    case wxID_CANCEL:
                        task->set_overwrite_prompt_result(2);
                        break;

                    default:
                        wxLogError("dlg.ShowModal() invalid return value");
                        task->set_overwrite_prompt_result(2);
                        break;
                }
            }
            
            bool cont;
            if (progress >= 0.f) {
                cont = dlg.Update((int)(progress * 999), msg);
            } else {
                cont = dlg.Pulse(msg);
            }

            if (!cont) {
                task = nullptr;
                break;
            }

            wxMilliSleep(10);
        }
    }

    Fetch();
}










